#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Run the validation suite and write ``docs/validation.md``.

Usage::

    python scripts/generate_validation_report.py            # run pytest -m validation, then write the report
    python scripts/generate_validation_report.py --junit results.xml   # reuse an existing junit file

The table of cases comes from ``validation/data/validation_cases.csv`` (reference value, source and
tolerance of every checked quantity); the status of each case comes from the junit XML of the pytest run;
the documented validity range of each model is read from the ``Validity`` paragraphs of the model docstrings.
"""
from __future__ import annotations

import argparse
import csv
import inspect
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import OrderedDict, defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CSV_FILE = os.path.join(ROOT, "validation", "data", "validation_cases.csv")
OUT_FILE = os.path.join(ROOT, "docs", "validation.md")

sys.path.insert(0, os.path.join(ROOT, "src"))


def run_pytest(junit_path: str) -> int:
    cmd = [sys.executable, "-m", "pytest", "tests/validation", "-m", "validation", "-q", "-p", "no:cacheprovider",
           "-W", "ignore", f"--junitxml={junit_path}"]
    return subprocess.call(cmd, cwd=ROOT)


def parse_junit(path: str):
    """Return ``{test_function_name: status}`` aggregated over parametrisations (fail > skip/xfail > pass)."""
    tree = ET.parse(path)
    status = {}
    counts = defaultdict(lambda: {"pass": 0, "fail": 0, "skip": 0})
    for case in tree.iter("testcase"):
        base = case.get("name").split("[", 1)[0]
        if case.find("failure") is not None or case.find("error") is not None:
            counts[base]["fail"] += 1
        elif case.find("skipped") is not None:
            counts[base]["skip"] += 1
        else:
            counts[base]["pass"] += 1
    for name, c in counts.items():
        if c["fail"]:
            status[name] = "FAIL"
        elif c["skip"] and not c["pass"]:
            status[name] = "SKIP / XFAIL"
        elif c["skip"]:
            status[name] = "PASS (partial skip)"
        else:
            status[name] = "PASS"
    return status, {k: sum(v.values()) for k, v in counts.items()}


def read_cases():
    with open(CSV_FILE, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def fmt_tol(t: str) -> str:
    kind, _, val = t.partition(":")
    return {"rel": "relative ", "abs": "absolute "}.get(kind, "") + val


def esc(s: str) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ")


def model_validity():
    import energysim.models as models
    from energysim.models.common import ModelComponent
    rows = []
    for name in sorted(dir(models)):
        cls = getattr(models, name)
        if not (inspect.isclass(cls) and issubclass(cls, ModelComponent) and cls is not ModelComponent):
            continue
        doc = inspect.getdoc(cls) or ""
        paras = re.split(r"\n\s*\n", doc)
        found = [p.replace("\n", " ").strip() for p in paras if re.search(r"\bvalidity\b", p, re.I)]
        text = ""
        for p in found:
            m = re.search(r"(Validity.*)", p, re.I | re.S)
            text += (m.group(1) if m else p) + " "
        if not text:
            # scattered sentences e.g. "Validity: ..." inside the paragraph
            m = re.search(r"(Validity[^\n]*(?:\n[ ]+[^\n]+)*)", doc)
            text = m.group(1).replace("\n", " ") if m else "not documented"
        rows.append((name, re.sub(r"\s+", " ", text).strip()))
    return rows


def build_report(status, counts) -> str:
    cases = read_cases()
    by_case = OrderedDict()
    for r in cases:
        by_case.setdefault(r["case"], []).append(r)

    lines = []
    w = lines.append
    w("# Validation")
    w("")
    w("*This page is generated by `scripts/generate_validation_report.py` from `validation/data/validation_cases.csv` "
      "and a run of `pytest -m validation`. Do not edit by hand.*")
    w("")
    n_tests = sum(counts.values())
    n_fail = sum(1 for s in status.values() if s == "FAIL")
    w(f"The suite contains **{n_tests} validation tests** covering **{len(cases)} checked quantities** in "
      f"{len(by_case)} cases; {n_fail} test function(s) failing in the run that produced this page.")
    w("")
    w("## What is validated, and against what")
    w("")
    w("Reference types used throughout:")
    w("")
    w("* **analytic** - a closed-form or textbook formula evaluated independently of the model code "
      "(Faraday's law, stoichiometry, exponential step responses, the Carnot bound, the isentropic work formula, ...).")
    w("* **cross-check** - an independent software implementation given identical inputs "
      "(`pvlib`, `pandapower` vs a hand-written complex fixed-point solver and the MATPOWER case9 solution, `PyPSA`).")
    w("* **self-consistency** - conservation laws or an equivalence between two code paths "
      "(energy and mass balances, world-driven run vs direct library call, re-run determinism).")
    w("")
    w("Where a source is cited it is a physical constant, a textbook formula or a named public data set; "
      "numeric reference values that are only approximately known (e.g. the compressibility of hydrogen at 350 bar) "
      "are labelled as such and checked with a correspondingly loose tolerance. Models are *surrogates for system-level "
      "studies*, not bankable simulators: the validity ranges below are part of the contract.")
    w("")
    w("## Cases")
    w("")
    w("| Case | Quantity | Reference | Source / citation | Tolerance | Status | Notes |")
    w("|---|---|---|---|---|---|---|")
    for case, rows in by_case.items():
        for r in rows:
            st = status.get(r["test"], "not run")
            w(f"| `{case}` | {esc(r['quantity'])} | {esc(r['reference_value'])} | {esc(r['source'])} | "
              f"{esc(fmt_tol(r['tolerance']))} | {st} | {esc(r['notes'])} |")
    w("")
    w("## Orchestrator findings")
    w("")
    w("* Zero-order-hold Jacobi coupling of a one-way cascade converges with observed order 1 against the analytic "
      "solution when each subsystem integrates exactly; Gauss-Seidel is also first order and never worse.")
    w("* Inside a strongly connected component Gauss-Seidel falls back to the Jacobi one-step delay, so the two schemes "
      "give identical results for genuinely cyclic systems.")
    w("* `extrapolation='linear'` extrapolates each exchanged value a *full* macro step ahead. It therefore predicts the "
      "end-of-step value of a smooth signal with second-order accuracy (versus first order for the hold), but because the "
      "receiver holds that value over the whole step, the coupled-ODE error is not reduced; extrapolating to the step "
      "midpoint would be the second-order choice. Linear extrapolation is only applied by Jacobi coupling.")
    w("")
    w("## Documented validity ranges per model")
    w("")
    w("Extracted from the model docstrings.")
    w("")
    w("| Model | Validity |")
    w("|---|---|")
    for name, text in model_validity():
        w(f"| `{name}` | {esc(text)} |")
    w("")
    w("## Reproducing")
    w("")
    w("```bash")
    w("python -m pytest tests/validation -m validation")
    w("python scripts/generate_validation_report.py")
    w("```")
    w("")
    w("`pvlib` and `pandapower`/`pypsa` cross-checks are skipped when the packages are not installed.")
    w("")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--junit", help="reuse an existing junit XML instead of running pytest")
    ap.add_argument("--out", default=OUT_FILE)
    args = ap.parse_args(argv)

    junit = args.junit
    rc = 0
    if not junit:
        junit = os.path.join(tempfile.mkdtemp(), "validation-junit.xml")
        rc = run_pytest(junit)
    status, counts = parse_junit(junit)
    text = build_report(status, counts)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {args.out}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
