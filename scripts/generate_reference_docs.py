def model_classes() -> dict:
    MC = _models.ModelComponent
    return {n: getattr(_models, n) for n in _models.__all__
            if inspect.isclass(getattr(_models, n)) and issubclass(getattr(_models, n), MC) and getattr(_models, n) is not MC}


def _annot(p: inspect.Parameter, default) -> str:
    if p.annotation is not inspect.Parameter.empty:
        a = p.annotation
        return a if isinstance(a, str) else getattr(a, "__name__", str(a))
    return type(default).__name__ if default is not inspect.Parameter.empty and default is not None else "-"


def param_table(cls, doc_params: dict) -> str:
    rows = ["| Parameter | Type | Default | Unit | Description |", "|---|---|---|---|---|"]
    sig = inspect.signature(cls.__init__)
    for name, p in sig.parameters.items():
        if name == "self" or p.kind in (p.VAR_KEYWORD, p.VAR_POSITIONAL):
            continue
        d = "required" if p.default is inspect.Parameter.empty else f"`{p.default!r}`"
        desc = doc_params.get(name, ("", ""))[1] or "-"
        rows.append(f"| `{name}` | `{_annot(p, p.default)}` | {d} | {unit_of(name)} | {esc(desc)} |")
    return "\n".join(rows)


def var_table(names, units: dict, docs: dict, kind: str) -> str:
    rows = [f"| {kind} | Unit | Description |", "|---|---|---|"]
    for n in names:
        desc = docs.get(n, ("", ""))[1] or "-"
        rows.append(f"| `{n}` | {units.get(n, 'unspecified')} | {esc(desc)} |")
    return "\n".join(rows)


def model_example(cls, slug: str) -> str:
    d = cls.describe_class()
    outs = ", ".join(repr(o) for o in d["outputs"][:3])
    var = re.sub(r"[^a-z0-9]+", "_", cls.__name__.lower()).strip("_")
    return (f"from energysim import world\nfrom energysim.models import {cls.__name__}\n\n"
            f"sim = world(start_time=0, stop_time=3600, t_macro=900)\n"
            f"sim.add_model({var!r}, model={cls.__name__}(), outputs=[{outs}], step_size=60)\n"
            f"res = sim.simulate()\nprint(res[{var!r}].tail(2))")


def render_model(cls, level: int) -> str:
    d = cls.describe_class()
    doc = inspect.getdoc(cls) or ""
    secs = split_sections(doc)
    pre = secs[0][1]
    named = {t.lower(): b for t, b in secs[1:]}
    doc_params = parse_entries(named.get("parameters", ""))
    in_docs = parse_entries(named.get("inputs", ""))
    out_docs = parse_entries(named.get("outputs", ""))
    h = "#" * level
    mod = cls.__module__
    parts = [f"> **Class**: `{cls.__name__}` | **Module**: `{mod}` | [Validation benchmarks](../validation.md) | "
             f"[Units](../units.md)\n",
             f"{h} Overview\n\n{to_markdown(pre)}\n",
             f"{h} Parameters\n\n{param_table(cls, doc_params)}\n",
             f"{h} Inputs\n\n{var_table(d['inputs'], d['units'], in_docs, 'Variable')}\n",
             f"{h} Outputs\n\n{var_table(d['outputs'], d['units'], out_docs, 'Variable')}\n"]
    for t, b in secs[1:]:
        tl = t.lower()
        if tl in ("parameters", "inputs", "outputs"):
            continue
        title = "Validity and notes" if tl == "notes" else t
        parts.append(render_section(title, b, level))
    if "notes" not in named:
        parts.append(f"{h} Validity and notes\n\n*No validity range is documented for this model yet.*\n")
    parts.append(f"{h} Usage example\n\n```python\n{model_example(cls, '')}\n```\n")
    return "\n".join(parts)


def render_model_page(slug, title, class_names) -> str:
    classes = model_classes()
    out = [BANNER, "", f"# {title}", ""]
    for cn in class_names:
        cls = classes[cn]
        if len(class_names) > 1:
            out += [f"## {cn}", "", render_model(cls, 3)]
        else:
            out.append(render_model(cls, 2))
    return "\n".join(out).rstrip() + "\n"


def render_catalog() -> str:
    cat = _models.catalog
    out = [BANNER, "", "# Equipment Catalog Archetypes", "",
           to_markdown(inspect.getdoc(cat) or ""), "",
           "## Archetypes", "",
           "| Factory | Builds | Provenance |", "|---|---|---|"]
    names = [n for n in cat.__all__ if n != "PROVENANCE"]
    generic = [n for n in names if not cat.PROVENANCE.get(n, "").startswith("DEPRECATED")]
    deprecated = [n for n in names if n not in generic]
    for n in generic:
        fn = getattr(cat, n)
        built = fn.__annotations__.get("return", "")
        built = built if isinstance(built, str) else getattr(built, "__name__", "")
        out.append(f"| `catalog.{n}` | `{built}` | {esc(cat.PROVENANCE.get(n, '-'))} |")
    out += ["", "## Deprecated manufacturer-named aliases", "",
            "These names emit a `DeprecationWarning` and will be removed. They are **not** backed by OEM datasheets.", "",
            "| Alias | Provenance |", "|---|---|"]
    for n in deprecated:
        out.append(f"| `catalog.{n}` | {esc(cat.PROVENANCE.get(n, '-'))} |")
    out += ["", "## Usage example", "", "```python",
            "from energysim import world", "from energysim.models import catalog", "",
            "sim = world(start_time=0, stop_time=3600, t_macro=900)",
            "bess = catalog.BESS_2h_2MW(name='bess', soc_init=0.5)",
            "sim.add_model('bess', model=bess, outputs=['P_actual', 'SoC'], step_size=60)",
            "res = sim.simulate()", "print(res['bess'].tail(2))", "```", ""]
    return "\n".join(out)


