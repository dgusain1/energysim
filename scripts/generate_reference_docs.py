_RULE = re.compile(r"^\s*(-{3,}|={3,})\s*$")
_ROLE = re.compile(r":(?:class|meth|func|mod|attr|data|exc|obj):`(~?)([^`]+)`")


def split_sections(doc: str):
    """Split a numpy-style docstring into ``[(title, text), ...]``; the first title is ``''``."""
    lines = doc.splitlines()
    out = [["", []]]
    i = 0
    while i < len(lines):
        if (i + 1 < len(lines) and lines[i].strip() and not lines[i].startswith(" ")
                and _RULE.match(lines[i + 1]) and len(lines[i + 1].strip()) >= 3):
            out.append([lines[i].strip(), []])
            i += 2
            continue
        out[-1][1].append(lines[i])
        i += 1
    return [(t, "\n".join(b).strip("\n")) for t, b in out]


def parse_entries(body: str):
    """Parse ``name : type`` + indented description entries -> ``{name: (type, description)}`` (ordered)."""
    entries = {}
    cur = None
    for ln in body.splitlines():
        if ln.strip() and not ln.startswith((" ", "\t")):
            head, _, typ = ln.partition(":")
            cur = [n.strip().strip("*`") for n in head.split(",") if n.strip()]
            for n in cur:
                entries[n] = [typ.strip(), []]
        elif cur and ln.strip():
            for n in cur:
                entries[n][1].append(ln.strip())
    return {n: (t, " ".join(d)) for n, (t, d) in entries.items()}


def _roles(text: str) -> str:
    def sub(m):
        name = m.group(2)
        if m.group(1) == "~":
            name = name.split(".")[-1]
        return f"`{name}`"

    return _ROLE.sub(sub, text)


def _is_list_item(s: str) -> bool:
    return bool(re.match(r"^\s*([-*+]|\d+[.)])\s+", s))


def to_markdown(text: str) -> str:
    """Convert docstring prose (rst-ish) to Markdown; code in docstrings is tagged ``no-test``."""
    text = _roles(text)
    lines = text.splitlines()
    out: list = []
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.rstrip().endswith("::"):
            head = ln.rstrip()[:-2].rstrip()
            out.append(head + ":" if head else "")
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            block = []
            while j < len(lines) and (lines[j].startswith("    ") or not lines[j].strip()):
                block.append(lines[j])
                j += 1
            while block and not block[-1].strip():
                block.pop()
            out += ["", f"```{NOTEST}"] + textwrap.dedent("\n".join(block)).splitlines() + ["```", ""]
            i = j
            continue
        if ln.lstrip().startswith(">>>"):
            block = []
            while i < len(lines) and lines[i].lstrip().startswith((">>>", "...")):
                block.append(re.sub(r"^\s*(>>>|\.\.\.) ?", "", lines[i]))
                i += 1
            out += ["", f"```{NOTEST}"] + block + ["```", ""]
            continue
        if _is_list_item(ln) and out and out[-1].strip() and not _is_list_item(out[-1]) \
                and not out[-1].startswith((" ", "\t")):
            out.append("")
        out.append(ln.rstrip())
        i += 1
    return "\n".join(out).strip("\n")


def access_table(body: str):
    """Leading lines of the form ``expr   description`` -> (markdown table, remaining text), else None."""
    rows = []
    lines = body.splitlines()
    k = 0
    while k < len(lines) and lines[k].strip():
        m = re.match(r"^(``.+?``)\s{2,}(\S.*)$", lines[k]) or re.match(r"^(``.+``)\s*()$", lines[k])
        if not m:
            break
        rows.append((m.group(1), m.group(2)))
        k += 1
    if not rows or (k < len(lines) and lines[k].strip()):
        return None
    table = "\n".join(["| Expression | Meaning |", "|---|---|"] + [f"| {esc(a)} | {esc(b)} |" for a, b in rows])
    return table, "\n".join(lines[k:]).strip()


def render_section(title: str, body: str, level: int) -> str:
    acc = access_table(body)
    if acc:
        table, rest = acc
        text = table + ("\n\n" + to_markdown(rest) if rest else "")
    else:
        text = to_markdown(body)
    return f"{'#' * level} {title}\n\n{text}\n"


def esc(s) -> str:
    """Make *s* safe for a Markdown table cell (roles resolved, rst double backticks -> single)."""
    return _roles(str(s)).replace("``", "`").replace("|", "\\|").replace("\n", " ")


def unit_of(name: str) -> str:
    low = name.lower()
    if low == "step_size":
        return "s"
    if low.startswith(("soc", "eta", "frac", "efficiency")):
        return "1"
    for suf, unit in sorted(SUFFIX_UNITS, key=lambda x: -len(x[0])):
        if low.endswith(suf):
            return unit
    return _units.infer_unit_from_name(name) or "-"


def sig_block(obj, name=None) -> str:
    name = name or obj.__name__
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return f"```{NOTEST}\n{name}(...)\n```"
    flat = f"{name}{sig}"
    if len(flat) > 100 and sig.parameters:
        params = [str(p) for p in sig.parameters.values()]
        flat = f"{name}(\n" + "".join(f"    {p},\n" for p in params) + ")"
    return f"```{NOTEST}\n{flat}\n```"


def plain_sig(fn, drop_first=True) -> str:
    """``name(a, b=1, *, c=None)`` without annotations."""
    ps = list(inspect.signature(fn).parameters.values())
    if drop_first and ps and ps[0].name in ("self", "cls"):
        ps = ps[1:]
    out = []
    for p in ps:
        if p.kind == p.VAR_POSITIONAL:
            out.append("*" + p.name)
        elif p.kind == p.VAR_KEYWORD:
            out.append("**" + p.name)
        elif p.default is inspect.Parameter.empty:
            out.append(p.name)
        else:
            out.append(f"{p.name}={p.default!r}")
    return "(" + ", ".join(out) + ")"


def first_line(obj) -> str:
    doc = inspect.getdoc(obj) or ""
    return doc.strip().splitlines()[0].strip() if doc.strip() else ""


