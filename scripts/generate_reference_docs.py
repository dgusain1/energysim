def render_fleet(slug, title, cname, kinds, how) -> str:
    cls = getattr(_container, cname)
    fleet = cls(size=2)
    secs = split_sections(inspect.getdoc(cls) or "")
    out = [BANNER, "", f"# {title}", "",
           f"> **Class**: `energysim.container.{cname}` | add to a world with `{how}` "
           f"(accepted kinds: {', '.join('`%s`' % k for k in kinds)})", "",
           "## Overview", "", to_markdown(secs[0][1]), ""]
    rows = ["| Parameter | Type | Default | Unit | Description |", "|---|---|---|---|---|"]
    for name, p in inspect.signature(cls.__init__).parameters.items():
        if name == "self" or p.kind in (p.VAR_KEYWORD, p.VAR_POSITIONAL):
            continue
        if name not in FLEET_PARAM_DOC:
            raise KeyError(f"generate_reference_docs: add a description for fleet parameter '{name}' ({cname})")
        unit, desc = FLEET_PARAM_DOC[name]
        a = p.annotation if isinstance(p.annotation, str) else getattr(p.annotation, "__name__", "-")
        rows.append(f"| `{name}` | `{a}` | `{p.default!r}` | {unit} | {desc} |")
    out += ["## Parameters", ""] + rows + [""]
    ins = list(fleet.input_values)
    sts = list(fleet.states)
    out += ["## Inputs", "", "| Variable | Unit | Aliases |", "|---|---|---|"]
    for n in ins:
        al = ", ".join(f"`{a}`" for a, t in fleet.aliases.items() if t == n) or "-"
        out.append(f"| `{n}` | {unit_of(n) if unit_of(n) != '-' else 'unspecified'} | {al} |")
    out += ["", "## Outputs", "", "| Variable | Unit | Aliases |", "|---|---|---|"]
    for n in sts:
        al = ", ".join(f"`{a}`" for a, t in fleet.aliases.items() if t == n) or "-"
        out.append(f"| `{n}` | {unit_of(n) if unit_of(n) != '-' else 'unspecified'} | {al} |")
    out += ["", "Every output `<var>` is also available as `total_<var>`, `mean_<var>`, `min_<var>`, `max_<var>` "
            "and per entity as `<var>[i]`. Units that read `unspecified` are not declared by the container; "
            "connections to or from them are never rescaled (see [Units](../units.md)).", ""]
    for t, b in secs[1:]:
        out.append(render_section(t, b, 2))
    out += ["## Validation", "",
            "The fleet is tested against an explicit loop of scalar models "
            "(`tests/strengths/test_vectorized_fleets.py`); see [Validation](../validation.md).", "",
            "## Usage example", "", "```python", FLEET_EXAMPLES[cname], "```", ""]
    return "\n".join(out)


