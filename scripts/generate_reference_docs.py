def render_class_reference(cls, level=2, methods=False, method_prefix=None) -> str:
    h = "#" * level
    secs = split_sections(inspect.getdoc(cls) or "")
    out = [f"{h} `{cls.__name__}`", "", f"*Module*: `{cls.__module__}`", "", sig_block(cls), ""]
    if secs[0][1]:
        out += [to_markdown(secs[0][1]), ""]
    for t, b in secs[1:]:
        if t.lower() == "parameters":
            ents = parse_entries(b)
            rows = ["| Parameter | Type | Description |", "|---|---|---|"]
            for n, (typ, desc) in ents.items():
                rows.append(f"| `{n}` | {esc(typ) or '-'} | {esc(_roles(desc)) or '-'} |")
            out += [f"{h}# Parameters", ""] + rows + [""]
        else:
            out.append(render_section("Validity and notes" if t.lower() == "notes" else t, b, level + 1))
    if methods:
        rows = ["| Method | Summary |", "|---|---|"]
        for n, m in inspect.getmembers(cls, predicate=inspect.isfunction):
            if n.startswith("_") or (method_prefix and not n.startswith(method_prefix)):
                continue
            if getattr(m, "__qualname__", "").split(".")[0] != cls.__name__:
                continue
            rows.append(f"| `{n}{plain_sig(m)}` | {esc(first_line(m))} |")
        if len(rows) > 2:
            out += [f"{h}# Methods", ""] + rows + [""]
    return "\n".join(out)


