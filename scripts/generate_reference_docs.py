def generate() -> dict:
    """Return ``{relative path under docs/: content}`` for every generated page."""
    files = {"physical-models.md": render_physical_models(), "components/catalog.md": render_catalog(),
             "containers/overview.md": render_containers_overview(),
             "containers/custom_fleet.md": render_custom_fleet(),
             "networks.md": render_networks(), "control.md": render_control(), "results.md": render_results()}
    for slug, title, cns in MODEL_PAGES:
        files[f"components/{slug}.md"] = render_model_page(slug, title, cns)
    for page in FLEET_PAGES:
        files[f"containers/{page[0]}.md"] = render_fleet(*page)
    covered = {cn for _, _, cns in MODEL_PAGES for cn in cns}
    missing = set(model_classes()) - covered
    if missing:
        raise SystemExit(f"model classes without a docs page (add them to MODEL_PAGES): {sorted(missing)}")
    return {k: v.replace("\r\n", "\n") for k, v in files.items()}


def write(files: dict, out_dir: str) -> None:
    for rel, content in files.items():
        path = os.path.join(out_dir, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf8", newline="\n") as fh:
            fh.write(content)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=os.path.join(ROOT, "docs"))
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed docs differ")
    args = ap.parse_args(argv)
    files = generate()
    if args.check:
        bad = []
        for rel, content in files.items():
            p = os.path.join(args.out, *rel.split("/"))
            cur = open(p, encoding="utf8", newline="").read().replace("\r\n", "\n") if os.path.exists(p) else None
            if cur != content:
                bad.append(rel)
        if bad:
            print("generated docs out of date: " + ", ".join(bad) + "\nrun: python scripts/generate_reference_docs.py",
                  file=sys.stderr)
            return 1
        return 0
    write(files, args.out)
    print(f"wrote {len(files)} pages to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
