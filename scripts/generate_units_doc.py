# -*- coding: utf-8 -*-
"""Generate docs/units.md from the energysim.units registry."""
import os
import sys

root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(root, "src"))

from energysim import units as U  # noqa: E402


def fmt(x):
    return f"{x:.10g}"


def render():
    s = U.UnitSystem.default()
    out = []
    w = out.append
    w("# Units\n")
    w("<!-- Generated by scripts/generate_units_doc.py. Do not edit by hand. -->\n")
    w("## Policy\n")
    w("* **Every variable has a unit.** A unit is either *declared*, derived from a conventional "
      "name suffix (`p_mw`, `t_in_degc`, `vm_pu`), or taken from the world's default unit for the "
      "quantity the name denotes (`P_cmd` is active power).")
    w("* **Undeclared means `unspecified`.** A variable whose unit cannot be determined is never "
      "silently scaled; connections between it and another unit raise instead of guessing.")
    w("* **One default unit per quantity.** The energysim standard system is listed below. It is "
      "shown in logs, `Results.units`, the `energysim units` CLI and these docs, and can be "
      "overridden per world.")
    w("* **No implicit physics.** Currencies (EUR vs USD), per-unit vs volts, and actual volume "
      "flow (`m3/h`) vs normal volume flow (`Nm3/h`) are different dimensions and are never "
      "converted. Unknown units and incompatible dimensions raise `ValueError`.")
    w("* **Lookup order.** Exact spelling first (`MV` is megavolt, `mV` millivolt), then a "
      "spelling-insensitive match that is used only when unambiguous (`kw`, `KW`, `kW_el` -> `kW`; "
      "`mv` is rejected as ambiguous).\n")
    w(f"Default system: `{s.name}` (hash `{s.hash}`).\n")

    w("## Default unit per quantity\n")
    w("| Quantity | Default unit | Carrier | Description | Accepted units |")
    w("|---|---|---|---|---|")
    for r in s.table():
        acc = ", ".join(f"`{u}`" for u in r["accepted_units"])
        w(f"| `{r['quantity']}` | `{r['default_unit']}` | {r['carrier']} | {r['description']} | {acc} |")
    w("")

    w("## Conversion factors\n")
    w("`default = value * factor + offset`. Factors are exact; `offset` is non-zero only for "
      "absolute temperatures.\n")
    cur = None
    for r in U.conversion_rows(s):
        if r["quantity"] != cur:
            cur = r["quantity"]
            w(f"\n### `{cur}` (to `{r['default_unit']}`)\n")
            w("| Unit | Factor | Offset |")
            w("|---|---|---|")
        w(f"| `{r['unit']}` | {fmt(r['factor'])} | {fmt(r['offset'])} |")
    w("")

    w("## Declaring units\n")
    w("**Components** declare units of their variables with a `units` attribute:\n")
    w("```python {.no-test}\nclass MyModel:\n    units = {'p_set': 'kW', 'temp_out': 'degC'}\n```\n")
    w("**External simulators / adapters**:\n")
    w("```python {.no-test}\nw.add_simulator('plant', 'plant.fmu', step_size=60, units={'P': 'W', 'T': 'K'})\n```\n")
    w("**Connections** convert explicitly with `from_unit` / `to_unit`:\n")
    w("```python {.no-test}\nw.add_connections([\n    {'from': 'plant.P', 'to': 'grid.p_mw', 'from_unit': 'W', 'to_unit': 'MW'},\n])\n```\n")
    w("**World default system** (overrides per quantity, or a preset):\n")
    w("```python {.no-test}\nw = world(..., unit_system={'active_power': 'MW', 'energy': 'MWh'})\nw = world(..., unit_system='si')\n```\n")
    w("**Python API**:\n")
    w("```python\nfrom energysim.units import UnitSystem, resolve_unit, infer_quantity\n\n"
      "us = UnitSystem.default()\nus.to_default(2.0, 'MW')        # 2000.0 (kW)\n"
      "us.convert(300, 'K', 'degC')     # 26.85\nus.format_table()                # aligned text table\n"
      "resolve_unit('P_cmd')            # ('kW', 'default-by-quantity')\n"
      "resolve_unit('p_mw')             # ('MW', 'suffix')\nresolve_unit('y')                # (None, 'unspecified')\n```\n")
    w("`resolve_unit` returns the unit together with its source: `declared`, `suffix`, "
      "`default-by-quantity` or `unspecified`.\n")

    w("## Where conventions show up\n")
    w("* **Log lines**: the world logs the active unit system (`UnitSystem.describe()`) at start and "
      "every applied conversion, plus a warning for each `unspecified` variable that is connected.")
    w("* **Python**: `UnitSystem.default().format_table()` prints the table above as aligned text.")
    w("* **Results**: `Results.units` maps every output variable to its unit (or `None` when unspecified); "
      "the unit-system name and hash are stored in the result metadata.\n")

    return "\n".join(out) + "\n"


def main():
    path = os.path.join(root, "docs", "units.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(render())
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
