"""Execute ``examples/notebooks/*.ipynb`` top to bottom with nbclient (marked ``slow``).

Notebooks run in a temporary copy (the stored outputs in the repository are never touched) with
``MPLBACKEND=Agg`` and the repository's ``src/`` on ``PYTHONPATH``. Skipped when nbclient/ipykernel are missing.
The notebooks are generated by ``scripts/generate_notebooks.py``.
"""
from __future__ import annotations

import os
import re
import shutil
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
NOTEBOOKS = sorted((ROOT / "examples" / "notebooks").glob("*.ipynb"))
CELL_TIMEOUT_S = 180


@pytest.mark.slow
@pytest.mark.parametrize("nb_path", NOTEBOOKS, ids=[p.stem for p in NOTEBOOKS])
def test_notebook_executes(nb_path, tmp_path, monkeypatch):
    nbformat = pytest.importorskip("nbformat")
    nbclient = pytest.importorskip("nbclient")
    pytest.importorskip("ipykernel")
    for mod in ("pandapower", "matplotlib"):
        pytest.importorskip(mod)

    work = tmp_path / nb_path.parent.name
    shutil.copytree(nb_path.parent, work, ignore=shutil.ignore_patterns("__pycache__", ".ipynb_checkpoints"))
    nb = nbformat.read(work / nb_path.name, as_version=4)

    monkeypatch.setenv("MPLBACKEND", "Agg")
    monkeypatch.setenv("PYTHONPATH", str(ROOT / "src") + os.pathsep + os.environ.get("PYTHONPATH", ""))
    monkeypatch.setenv("PYTHONIOENCODING", "utf-8")
    client = nbclient.NotebookClient(nb, timeout=CELL_TIMEOUT_S, kernel_name="python3",
                                     resources={"metadata": {"path": str(work)}})
    try:
        client.execute()
    except nbclient.exceptions.CellExecutionError as exc:
        msg = re.sub(r"\[[0-9;]*m", "", str(exc))
        pytest.fail(f"{nb_path.name}: {msg[-1500:]}")
